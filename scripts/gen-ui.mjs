const chart = (letters) => {
  const rows = [];
  for (let r = 0; r < 3; r++) {
    const cells = [];
    for (let c = 0; c < 3; c++) {
      const letter = letters[r * 3 + c];
      cells.push(
        letter
          ? `    <div id="k-${letter}" class="cell"><div id="kl-${letter}" class="cell-letter">${letter}</div></div>`
          : `    <div class="cell-empty"></div>`,
      );
    }
    rows.push(`  <div class="row">\n${cells.join('\n')}\n  </div>`);
  }
  return `<!-- Generated by scripts/gen-ui.mjs. A 3D hand floats in front of each cell. -->
<style>
  .root {
    flex-direction: column;
    gap: 1;
    padding-top: 1;
    padding-bottom: 1;
    padding-left: 1;
    padding-right: 1;
    border-radius: 2;
    border-width: 0.2;
    border-color: #343a48;
    background-color: #12141a;
  }
  .row { flex-direction: row; gap: 1; }
  .cell {
    flex-direction: column;
    width: 10;
    height: 13;
    align-items: center;
    justify-content: flex-end;
    padding-bottom: 0.3;
    border-radius: 1;
    border-width: 0.3;
    border-color: #3a4050;
    background-color: #181b23;
  }
  .cell-empty { width: 10; height: 13; }
  .cell-letter { color: #f4f5f7; font-size: 2.4; font-weight: 700; }
</style>
<div class="root">
${rows.join('\n')}
</div>
`;
};
writeFileSync('public/ui/chart-left.uikitml', chart([...'ABCDEFGHI']));
writeFileSync('public/ui/chart-right.uikitml', chart([...'LORUVWXY']));
